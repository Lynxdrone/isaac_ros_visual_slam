"""cuVSLAM with the real ZED cameras of the AMIAD rig, using the Kalibr camera-IMU calibration against the
Epson IMU (config/amiad_<n>cam_kalibr_epson.yaml, generated by Camera_IMU_Calibration_Datasets/Amiad/
make_slam_configs.py). The cameras (and their order) come from the yaml: cam0..camN, (0,1), (2,3), ... pairs.
    num_cameras:=6 (default): front, rear, left
    num_cameras:=8: + right (mirror of the left pair about the IMU, the right ZED has no usable calibration)

Extrinsics: static TFs imu_frame -> kalibr_zed_<arm>_<eye>_optical_frame (pose of each camera in the IMU
frame = inverse of Kalibr T_cam_imu). Own frame names, so they never clash with the ZED wrapper TFs.
Intrinsics: amiad_kalibr_camera_info.py publishes a CameraInfo per image from the same yaml (the bags
have no camera_info for the left eyes nor for the gray images).

tracking_mode:=0 (default): multicamera, all cameras, no IMU (cuVSLAM VIO only supports one stereo pair).
tracking_mode:=1: VIO with the front pair + /imu/data (Epson noise from the same IMU calibration).

From a bag (played with its clock):
    ros2 launch isaac_ros_visual_slam isaac_ros_visual_slam_amiad_kalibr.launch.py num_cameras:=8
    ros2 bag play <bag> --clock
Live ZED wrapper: use_sim_time:=false

Inputs (camera index -> topic): 0,1 front  2,3 rear  4,5 left  6,7 right   (camN.rostopic of the yaml)
Outputs: map -> odom -> imu_link TF (base_frame:= to change), /visual_slam/tracking/odometry, ...
"""
import os
import re

import launch
import yaml
from ament_index_python.packages import get_package_share_directory
from launch.actions import DeclareLaunchArgument, ExecuteProcess, OpaqueFunction
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import ComposableNodeContainer, Node
from launch_ros.descriptions import ComposableNode

# camN.rostopic -> (arm, eye) for the frame / camera_info names
TOPIC_RE = re.compile(r'/zed_(\w+?)/zed_node/(left|right)/')

# Epson IMU (imu_epson.yaml, Allan variance), inflated x10 like the MINS/Basalt configs
IMU_NOISE = {
    'gyro_noise_density': 2.5168513991925153e-04,
    'gyro_random_walk': 4.878091752029107e-06,
    'accel_noise_density': 5.457397459599346e-03,
    'accel_random_walk': 6.113996506614726e-04,
    'calibration_frequency': 400.0,
}


try:
    CONFIG_DIR = os.path.join(get_package_share_directory('isaac_ros_visual_slam'), 'config')
except Exception:  # launched from the source tree, package not installed here
    CONFIG_DIR = os.path.join(os.path.dirname(os.path.realpath(__file__)), '..', 'config')


def inv(T):
    R = [[T[j][i] for j in range(3)] for i in range(3)]
    t = [-sum(R[i][j] * T[j][3] for j in range(3)) for i in range(3)]
    return R, t


def rot_to_quat(R):
    import math
    tr = R[0][0] + R[1][1] + R[2][2]
    w = math.sqrt(max(0.0, 1.0 + tr)) / 2.0
    x = math.copysign(math.sqrt(max(0.0, 1.0 + R[0][0] - R[1][1] - R[2][2])) / 2.0, R[2][1] - R[1][2])
    y = math.copysign(math.sqrt(max(0.0, 1.0 - R[0][0] + R[1][1] - R[2][2])) / 2.0, R[0][2] - R[2][0])
    z = math.copysign(math.sqrt(max(0.0, 1.0 - R[0][0] - R[1][1] + R[2][2])) / 2.0, R[1][0] - R[0][1])
    n = math.sqrt(x * x + y * y + z * z + w * w)
    return x / n, y / n, z / n, w / n


def launch_setup(context):
    calib_path = LaunchConfiguration('calib').perform(context) or os.path.join(
        CONFIG_DIR, f"amiad_{LaunchConfiguration('num_cameras').perform(context)}cam_kalibr_epson.yaml")
    imu_frame = LaunchConfiguration('imu_frame').perform(context)
    base_frame = LaunchConfiguration('base_frame').perform(context) or imu_frame
    tracking_mode = int(LaunchConfiguration('tracking_mode').perform(context))
    use_sim_time = LaunchConfiguration('use_sim_time').perform(context).lower() == 'true'
    publish_tf = LaunchConfiguration('publish_tf').perform(context).lower() == 'true'
    with open(calib_path) as f:
        calib = yaml.safe_load(f)

    # Order matters: cuVSLAM treats cameras (0,1), (2,3), ... as stereo pairs (= yaml cam0..camN)
    cameras = []
    for idx in range(len([k for k in calib if re.fullmatch(r'cam\d+', k)])):
        match = TOPIC_RE.search(calib[f'cam{idx}']['rostopic'])
        if not match:
            raise RuntimeError(f"cam{idx} of {calib_path}: cannot parse {calib[f'cam{idx}']['rostopic']}")
        cameras.append(match.groups())
    if tracking_mode == 1:
        cameras = cameras[:2]  # VIO: front pair only

    actions, remappings, optical_frames, image_topics, info_topics = [], [], [], [], []
    for idx, (arm, eye) in enumerate(cameras):
        cam = calib[f'cam{idx}']
        frame = f'kalibr_zed_{arm}_{eye}_optical_frame'
        image_topic = cam['rostopic']
        info_topic = f'/kalibr/zed_{arm}/{eye}/camera_info'
        R, t = inv(cam['T_cam_imu'])  # pose of the camera in the IMU frame
        q = rot_to_quat(R)
        actions.append(Node(
            package='tf2_ros', executable='static_transform_publisher',
            name=f'tf_kalibr_zed_{arm}_{eye}',
            arguments=['--x', str(t[0]), '--y', str(t[1]), '--z', str(t[2]),
                       '--qx', str(q[0]), '--qy', str(q[1]), '--qz', str(q[2]), '--qw', str(q[3]),
                       '--frame-id', imu_frame, '--child-frame-id', frame],
            parameters=[{'use_sim_time': use_sim_time}]))
        remappings += [(f'visual_slam/image_{idx}', image_topic),
                       (f'visual_slam/camera_info_{idx}', info_topic)]
        optical_frames.append(frame)
        image_topics.append(image_topic)
        info_topics.append(info_topic)

    if base_frame != imu_frame:
        print(f'[amiad_kalibr] base_frame {base_frame} != imu_frame {imu_frame}: '
              f'a {base_frame} -> {imu_frame} TF must be published by someone else')

    ros_args = ['--ros-args', '-p', f'use_sim_time:={str(use_sim_time).lower()}']
    actions.append(ExecuteProcess(
        cmd=['python3', os.path.join(os.path.dirname(os.path.realpath(__file__)), 'amiad_kalibr_camera_info.py'),
             '--calib', calib_path, '--image-topics', *image_topics, '--info-topics', *info_topics,
             '--frames', *optical_frames, *ros_args],
        name='kalibr_camera_info', output='screen'))

    if tracking_mode == 1:
        remappings.append(('visual_slam/imu', LaunchConfiguration('imu_topic').perform(context)))

    visual_slam_node = ComposableNode(
        name='visual_slam_node',
        package='isaac_ros_visual_slam',
        plugin='nvidia::isaac_ros::visual_slam::VisualSlamNode',
        remappings=remappings,
        parameters=[{
            'use_sim_time': use_sim_time,
            'tracking_mode': tracking_mode,
            'num_cameras': len(cameras),
            'min_num_images': len(cameras),
            'camera_optical_frames': optical_frames,
            'base_frame': base_frame,
            'imu_frame': imu_frame,
            'odom_frame': 'odom',
            'map_frame': 'map',
            'publish_odom_to_base_tf': publish_tf,
            'publish_map_to_odom_tf': publish_tf,
            # Kalibr intrinsics are for the ZED images as recorded, with their (small) radtan distortion:
            # camera_info carries plumb_bob, so the cameras are not treated as a rectified stereo rig
            'rectified_images': False,
            'enable_image_denoising': False,
            # the 3 ZED streams are stamped independently
            'sync_matching_threshold_ms': float(LaunchConfiguration('sync_ms').perform(context)),
            'image_jitter_threshold_ms': float(LaunchConfiguration('jitter_ms').perform(context)),
            **IMU_NOISE,
            'enable_slam_visualization': True,
            'enable_observations_view': True,
            'enable_landmarks_view': True,
        }])

    actions.append(ComposableNodeContainer(
        name='visual_slam_launch_container',
        namespace='',
        package='rclcpp_components',
        executable='component_container_mt',
        composable_node_descriptions=[visual_slam_node],
        output='screen',
    ))
    return actions


def generate_launch_description():
    return launch.LaunchDescription([
        DeclareLaunchArgument('num_cameras', default_value='6',
                              description='6 (front, rear, left) or 8 (+ right): picks config/amiad_<n>cam_kalibr_epson.yaml'),
        DeclareLaunchArgument('calib', default_value='',
                              description='merged Kalibr camchain-imucam yaml (overrides num_cameras)'),
        DeclareLaunchArgument('tracking_mode', default_value='0',
                              description='0: multicamera (6 cams, no IMU), 1: VIO (front pair + IMU)'),
        DeclareLaunchArgument('imu_frame', default_value='imu_link',
                              description='frame of the Epson IMU, parent of the camera frames'),
        DeclareLaunchArgument('base_frame', default_value='',
                              description='frame cuVSLAM tracks (default: imu_frame)'),
        DeclareLaunchArgument('imu_topic', default_value='/imu/data', description='IMU topic (tracking_mode 1)'),
        DeclareLaunchArgument('use_sim_time', default_value='true',
                              description='true for bag playback with --clock'),
        DeclareLaunchArgument('publish_tf', default_value='true',
                              description='broadcast map -> odom -> base_frame'),
        DeclareLaunchArgument('sync_ms', default_value='20.0',
                              description='max stamp difference between the images of one frame'),
        DeclareLaunchArgument('jitter_ms', default_value='60.0',
                              description='max delta between frames before a warning'),
        OpaqueFunction(function=launch_setup),
    ])
